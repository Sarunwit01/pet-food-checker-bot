/**
 * คลีนและแก้ไขคำพิมพ์ผิดระดับประโยค (รันก่อนส่งเข้า Handler ทุกตัว)
 * @param {string} text
 * @returns {string}
 */
function normalizeThaiTypos(text) {
  if (!text || typeof text !== 'string') return '';

  let s = text
    // 1. แปลงสระ เ สองตัวติดกันเป็น แ และนิคหิต+สระอา เป็น สระอำ
    .replace(/เเ/g, 'แ')
    .replace(/\u0E4D\u0E32/g, 'ำ')
    .replace(/\u0E32\u0E4D/g, 'ำ')
    // 2. แก้กรณีพิมพ์สระล่าง (ุ, ู) ซ้อนกับสระบน (ั, ิ, ี, ึ, ื, ็) บนพยัญชนะตัวเดียวกัน เช่น "หมายถุึง" -> "หมายถึง"
    .replace(/([\u0E38\u0E39])([\u0E31\u0E34-\u0E37\u0E47])/g, '$2')
    .replace(/([\u0E31\u0E34-\u0E37\u0E47])([\u0E38\u0E39])/g, '$1')
    // 3. ลดรูปสระหรือวรรณยุกต์ที่ถูกกดซ้ำติดกัน เช่น "น้ำำ" -> "น้ำ"
    .replace(/([\u0E31\u0E33-\u0E3A\u0E47-\u0E4E])\1+/g, '$1');

  // 4. แทนที่คำผิดยอดฮิตจากพจนานุกรม
  for (const [wrong, right] of COMMON_TYPO_REPLACEMENTS) {
    if (s.includes(wrong)) {
      s = s.split(wrong).join(right);
    }
  }

  return s;
}

/**
 * แปลงคำภาษาไทยเป็นรหัสเสียงพ้อง (Thai Phonetic Key)
 * เพื่อจับคู่คำที่สะกดคนละรูปแต่ออกเสียงเหมือนกัน เช่น:
 * - "ชอกโกแลด" == "ช็อกโกแลต"
 * - "ลูกเกต" == "ลูกเกด"
 * - "บร็อคโคลี่" == "บรอกโคลี"
 * - "แคนตาลุป" == "แคนตาลูป"
 * @param {string} str
 * @returns {string}
 */
function toThaiPhonetic(str) {
  if (!str) return '';

  let s = normalizeThaiTypos(str)
    .toLowerCase()
    // ตัดตัวอักษรและสระที่ถูกควบด้วยตัวการันต์ เช่น "ิร์", "ร์", "ด์", "ต์", "ย์"
    .replace(/[\u0E01-\u0E2E][\u0E31\u0E34-\u0E39]?\u0E4C/g, '')
    // ตัดไม้ไต่คู้ วรรณยุกต์ และตัวการันต์ที่เหลือ
    .replace(/[\u0E47-\u0E4E]/g, '')
    // ยุบสระเสียงสั้น-ยาวที่คนมักพิมพ์สลับกันให้เป็นรูปเดียวเพื่อเทียบเสียง
    .replace(/ใ/g, 'ไ')
    .replace(/รร/g, 'ัน')
    .replace(/ี/g, 'ิ')
    .replace(/ื/g, 'ึ')
    .replace(/ู/g, 'ุ')
    .replace(/ะ/g, '')
    // ยุบตัวอักษรซ้ำติดกัน เช่น "องุ่นน" -> "องุน"
    .replace(/(.)\1+/g, '$1')
    .trim();

  // ยุบกลุ่มพยัญชนะเสียงเดียวกัน (ทั้งพยัญชนะต้นและตัวสะกด แม่กก, แม่กด, แม่กบ, แม่กน)
  s = s
    .replace(/[ขฃคฅฆ]/g, 'ก')
    .replace(/[จฉชซฌฎฏฐฑฒตถทธศษส]/g, 'ด')
    .replace(/[ปผฝพฟภ]/g, 'บ')
    .replace(/[ญณรลฬ]/g, 'น');

  return s.replace(/\s+/g, '');
}

